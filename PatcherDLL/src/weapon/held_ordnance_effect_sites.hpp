inline bool verify(uintptr_t base, const build_sites& build)
{
   const uintptr_t delta = base - 0x400000u;
   for (unsigned n = 0; n != build.signatureCount; ++n) {
      const signature& sig = build.signatures[n];
      const auto* actual = reinterpret_cast<const uint8_t*>(sig.va + delta);
      unsigned relocation = 0;
      for (unsigned byte = 0; byte != sig.length;) {
         if (relocation < sig.relocationCount && byte == sig.relocations[relocation]) {
            uint32_t expected, value;
            std::memcpy(&expected, sig.bytes + byte, 4);
            std::memcpy(&value, actual + byte, 4);
            if (value != expected + static_cast<uint32_t>(delta)) return false;
            byte += 4;
            ++relocation;
         }
         else {
            if (actual[byte] != sig.bytes[byte]) return false;
            ++byte;
         }
      }
   }
   const auto* table = reinterpret_cast<const uintptr_t*>(build.cannonTable + delta);
   for (unsigned i = 0; i != 7; ++i) {
      if (i != 2 && table[kSlots[i]] != build.targets[i] + delta) return false;
   }
   const auto* classTable = reinterpret_cast<const uintptr_t*>(build.classTable + delta);
   for (unsigned i = 0; i != 3; ++i) {
      if (classTable[kClassSlots[i]] != build.classTargets[i] + delta) return false;
   }
   return true;
}

