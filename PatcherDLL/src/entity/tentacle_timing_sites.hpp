inline bool resolve_network_state(uintptr_t exeBase, GameBuild build, network_state& out)
{
   const sites::build_sites* selected;
   switch (build) {
   case GameBuild::Modtools:
      selected = &sites::kDebug;
      break;
   case GameBuild::Steam:
      selected = &sites::kSteam;
      break;
   case GameBuild::GOG:
      selected = &sites::kGog;
      break;
   default:
      return false;
   }
   if (!sites::matches(exeBase, selected->timing) || !sites::matches(exeBase, selected->getRatio))
      return false;

   // The debug timing prefix calls an import-style intra-image thunk. Verify
   // that it still leads to the separately verified GetTurnRatio leaf.
   if (build == GameBuild::Modtools) {
      const uint8_t* thunk = (const uint8_t*)resolve(exeBase, 0x00401316);
      int32_t displacement;
      std::memcpy(&displacement, thunk + 1, sizeof(displacement));
      if (thunk[0] != 0xE9 || thunk + 5 + displacement != resolve(exeBase, selected->ratio))
         return false;
   }
   out = {
      (const volatile uint8_t*)resolve(exeBase, selected->selector),
      (const volatile uint8_t*)resolve(exeBase, selected->clear),
      (const volatile uint8_t*)resolve(exeBase, selected->set),
      (const volatile uint8_t*)resolve(exeBase, selected->locked),
      (get_turn_ratio_t)resolve(exeBase, selected->ratio),
   };
   return true;
}

