inline bool matches(uintptr_t exeBase, const signature& expected)
{
   const uint8_t* actual = (const uint8_t*)resolve(exeBase, expected.va);
   uint16_t nextOperand = 0;
   for (uint16_t i = 0; i < expected.size;) {
      if (nextOperand < expected.operandCount && i == expected.operands[nextOperand]) {
         uint32_t stockAddress, actualAddress;
         std::memcpy(&stockAddress, expected.bytes + i, sizeof(stockAddress));
         std::memcpy(&actualAddress, actual + i, sizeof(actualAddress));
         if (actualAddress != (uintptr_t)resolve(exeBase, stockAddress)) return false;
         i += sizeof(uint32_t);
         ++nextOperand;
      }
      else {
         if (actual[i] != expected.bytes[i]) return false;
         ++i;
      }
   }
   return true;
}

